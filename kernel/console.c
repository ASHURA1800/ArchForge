/* ====================================================================
 * console_init — Initialize framebuffer console
 * ==================================================================== */
void console_init(void) {
    if (framebuffer_request.response == NULL ||
        framebuffer_request.response->framebuffer_count == 0) {
        serial_write("[CONSOLE] No framebuffer available!\n");
        return;
    }

    fb = framebuffer_request.response->framebuffers[0];
    fb_width = fb->width;
    fb_height = fb->height;
    fb_pitch = fb->pitch;
    fb_bpp = fb->bpp;

    /* Framebuffer address from Limine is already VIRTUAL (mapped by Limine).
     * Use it directly. */
    fb_addr = (uint32_t *)fb->address;

    console_cols = fb_width / FONT_WIDTH;
    console_rows = fb_height / FONT_HEIGHT;

    serial_write("[CONSOLE] Framebuffer: ");
    serial_write_dec(fb_width);
    serial_write("x");
    serial_write_dec(fb_height);
    serial_write(" bpp=");
    serial_write_dec(fb_bpp);
    serial_write(" pitch=");
    serial_write_dec(fb_pitch);
    serial_write("\n");
    serial_write("[CONSOLE] Console: ");
    serial_write_dec(console_cols);
    serial_write("x");
    serial_write_dec(console_rows);
    serial_write(" chars\n");

    console_clear();
}

/* ====================================================================
 * draw_char — Draw a single character at (row, col)
 * ==================================================================== */
static void draw_char(char c, size_t row, size_t col, uint32_t fg, uint32_t bg) {
    if (row >= console_rows || col >= console_cols) return;
    if (c < 32 || c > 127) c = '?';

    const uint8_t *glyph = font_8x16[c - 32];
    uint32_t *line = fb_addr + row * FONT_HEIGHT * (fb_pitch / 4) + col * FONT_WIDTH;

    for (int y = 0; y < FONT_HEIGHT; y++) {
        uint8_t bits = glyph[y];
        uint32_t *pixel = line;
        for (int x = 0; x < FONT_WIDTH; x++) {
            *pixel++ = (bits & (0x80 >> x)) ? fg : bg;
        }
        line += fb_pitch / 4;
    }
}

/* ====================================================================
 * console_putc — Write a single character
 * ==================================================================== */
void console_putc(char c) {
    if (!fb_addr) return;

    if (c == '\n') {
        cursor_col = 0;
        cursor_row++;
        if (cursor_row >= console_rows) {
            console_scroll();
            cursor_row = console_rows - 1;
        }
        return;
    }

    if (c == '\r') {
        cursor_col = 0;
        return;
    }

    if (c == '\b') {
        if (cursor_col > 0) {
            cursor_col--;
            draw_char(' ', cursor_row, cursor_col, COLOR_FG, COLOR_BG);
        }
        return;
    }

    if (c == '\t') {
        cursor_col = (cursor_col + 4) & ~3;
        if (cursor_col >= console_cols) {
            cursor_col = 0;
            cursor_row++;
        }
        if (cursor_row >= console_rows) {
            console_scroll();
            cursor_row = console_rows - 1;
        }
        return;
    }

    draw_char(c, cursor_row, cursor_col, COLOR_FG, COLOR_BG);

    cursor_col++;
    if (cursor_col >= console_cols) {
        cursor_col = 0;
        cursor_row++;
        if (cursor_row >= console_rows) {
            console_scroll();
            cursor_row = console_rows - 1;
        }
    }
}

/* ====================================================================
 * console_write — Write a string
 * ==================================================================== */
void console_write(const char *str) {
    while (*str) {
        console_putc(*str++);
    }
}

/* ====================================================================
 * console_write_hex — Write hex value
 * ==================================================================== */
void console_write_hex(uint64_t value) {
    static const char *hex = "0123456789ABCDEF";
    char buf[18];
    int i = 0;
    buf[i++] = '0';
    buf[i++] = 'x';
    for (int shift = 60; shift >= 0; shift -= 4) {
        buf[i++] = hex[(value >> shift) & 0xF];
    }
    buf[i] = '\0';
    console_write(buf);
}

/* ====================================================================
 * console_write_dec — Write decimal value
 * ==================================================================== */
void console_write_dec(uint64_t value) {
    char buf[24];
    int i = 0;
    if (value == 0) {
        buf[i++] = '0';
    } else {
        char rev[24];
        int j = 0;
        while (value > 0) {
            rev[j++] = '0' + (value % 10);
            value /= 10;
        }
        while (j > 0) {
            buf[i++] = rev[--j];
        }
    }
    buf[i] = '\0';
    console_write(buf);
}

/* ====================================================================
 * console_clear — Clear the screen
 * ==================================================================== */
void console_clear(void) {
    if (!fb_addr) return;
    size_t total_pixels = fb_width * fb_height;
    for (size_t i = 0; i < total_pixels; i++) {
        fb_addr[i] = COLOR_BG;
    }
    cursor_row = 0;
    cursor_col = 0;
}

/* ====================================================================
 * console_scroll — Scroll up by one line
 * ==================================================================== */
void console_scroll(void) {
    if (!fb_addr) return;

    size_t line_bytes = fb_pitch * FONT_HEIGHT;
    size_t total_lines = fb_height - FONT_HEIGHT;

    /* Move all lines up */
    for (size_t y = 0; y < total_lines; y++) {
        uint32_t *dst = fb_addr + y * (fb_pitch / 4);
        uint32_t *src = fb_addr + (y + FONT_HEIGHT) * (fb_pitch / 4);
        for (size_t x = 0; x < fb_width; x++) {
            dst[x] = src[x];
        }
    }

    /* Clear bottom line */
    uint32_t *last_line = fb_addr + total_lines * (fb_pitch / 4);
    for (size_t x = 0; x < fb_width; x++) {
        last_line[x] = COLOR_BG;
    }
}

/* ====================================================================
 * console_set_cursor — Set cursor position
 * ==================================================================== */
void console_set_cursor(size_t row, size_t col) {
    if (row < console_rows) cursor_row = row;
    if (col < console_cols) cursor_col = col;
}

/* ====================================================================
 * console_get_cursor — Get cursor position
 * ==================================================================== */
void console_get_cursor(size_t *row, size_t *col) {
    if (row) *row = cursor_row;
    if (col) *col = cursor_col;
}